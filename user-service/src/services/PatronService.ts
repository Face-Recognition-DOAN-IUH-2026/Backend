import bcrypt from 'bcryptjs';
import { AppDataSource } from '../data-source';
import { User } from '../entities/User.entity';
import { PatronRepository } from '../repositories/PatronRepository';
import { RedisService } from './RedisService';
import {
  PatronPublicDto,
  CreatePatronDto,
  UpdatePatronDto,
  LookupResultDto,
  SearchResultDto,
} from '../dto';
import { ConflictError, NotFoundError, BadRequestError } from '../errors';
import { checkActiveBorrows } from '../clients/BorrowServiceClient';
import { faceServiceClient } from '../clients/FaceServiceClient';
import { accessServiceClient } from '../clients/AccessServiceClient';

export class PatronService {
  constructor(
    private patronRepo: PatronRepository,
    private redis: RedisService,
  ) {}

  async search(
    query?: string,
    status?: string,
    skip = 0,
    limit = 20,
  ): Promise<SearchResultDto> {
    const [patrons, total] = await this.patronRepo.findPatrons({
      query,
      status,
      skip,
      limit,
    });
    return {
      items: await Promise.all(patrons.map((p) => this.toPatronPublic(p))),
      total,
    };
  }

  async lookup(
    studentCode?: string,
    cardNumber?: string,
  ): Promise<LookupResultDto> {
    let patron = studentCode
      ? await this.patronRepo.findByStudentCode(studentCode)
      : cardNumber
        ? await this.patronRepo.findByCardNumber(cardNumber)
        : null;

    if (!patron) {
      return { exists: false, patron: null, hasFace: false, isExpired: false };
    }

    const isExpired =
      !!patron.membershipExpiry && new Date(patron.membershipExpiry) < new Date();

    let hasFace = false;
    try {
      hasFace = await faceServiceClient.checkEnrollment(patron.id);
    } catch (error) {
      // Default to false if face service is unavailable
    }

    return {
      exists: true,
      patron: await this.toPatronPublic(patron),
      hasFace,
      isExpired,
    };
  }

  async getById(id: string): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');
    return await this.toPatronPublic(patron);
  }

  async create(dto: CreatePatronDto): Promise<PatronPublicDto> {
    const dupCode = await this.patronRepo.findByStudentCode(dto.studentCode);
    if (dupCode) throw new ConflictError('Student code already exists');

    const dupCard = await this.patronRepo.findByCardNumber(
      `THV-${dto.studentCode}`,
    );
    if (dupCard) throw new ConflictError('Student code already exists');

    const DEFAULT_PASSWORD = '11111111';
    const passwordHash = await bcrypt.hash(DEFAULT_PASSWORD, 10);

    const patron = await this.patronRepo.create({
      email: dto.email ?? `${dto.studentCode}@library.local`,
      passwordHash,
      fullName: dto.fullName,
      role: 'patron',
      studentCode: dto.studentCode,
      className: dto.className ?? null,
      course: dto.course ?? null,
      permanentAddress: dto.permanentAddress ?? null,
      cardNumber: `THV-${dto.studentCode}`,
      membershipExpiry: dto.membershipExpiry,
      issueDate: dto.issueDate ?? new Date().toISOString().split('T')[0],
      identityNumber: dto.identityNumber ?? null,
      phone: dto.phone ?? null,
      status: 'active',
      currentStatus: 'outside',
      passwordAutoGenerated: true,
    });

    return await this.toPatronPublic(patron);
  }

  async update(id: string, dto: UpdatePatronDto): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    const updated = await this.patronRepo.update(id, {
      fullName: dto.fullName,
      className: dto.className,
      course: dto.course,
      permanentAddress: dto.permanentAddress,
      identityNumber: dto.identityNumber,
      email: dto.email,
      phone: dto.phone,
      membershipExpiry: dto.membershipExpiry,
      status: dto.status as any,
    });

    return await this.toPatronPublic(updated!);
  }

  async deletePatron(id: string): Promise<{ deleted: boolean; id: string; soft: boolean }> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    const { hasActive } = await checkActiveBorrows(id).catch(() => {
      throw new ConflictError('Không thể kiểm tra sách đang mượn. Vui lòng thử lại sau.');
    });
    if (hasActive) {
      throw new ConflictError('Không thể xóa độc giả đang mượn sách. Vui lòng xử lý sách trước khi xóa.');
    }

    const queryRunner = AppDataSource.createQueryRunner();
    await queryRunner.connect();
    await queryRunner.startTransaction();

    try {
      await queryRunner.manager.update(User, id, { status: 'deleted' as any });
      await this.redis.publishUserDeleted(id, patron.email);
      await queryRunner.commitTransaction();
    } catch (error) {
      await queryRunner.rollbackTransaction();
      throw error;
    } finally {
      await queryRunner.release();
    }

    return { deleted: true, id, soft: true };
  }

  async restorePatron(id: string): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    if (patron.status !== 'deleted') {
      throw new BadRequestError('Patron is not deleted');
    }

    let newExpiry: string;
    const membershipExpiry = patron.membershipExpiry ? new Date(patron.membershipExpiry) : null;

    if (membershipExpiry && membershipExpiry >= new Date()) {
      newExpiry = membershipExpiry.toISOString().split('T')[0];
    } else {
      const oneYearFromNow = new Date();
      oneYearFromNow.setFullYear(oneYearFromNow.getFullYear() + 1);
      newExpiry = oneYearFromNow.toISOString().split('T')[0];
    }

    await this.patronRepo.update(id, {
      status: 'active',
      membershipExpiry: newExpiry,
    });

    const restored = await this.patronRepo.findById(id);
    if (!restored) throw new NotFoundError('Patron not found after restore');

    this.redis.publishUserUpdated(restored.id, restored.email);

    return await this.toPatronPublic(restored);
  }

  async changePassword(id: string, currentPassword: string | null, newPassword: string): Promise<void> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    if (!patron.passwordAutoGenerated) {
      if (!currentPassword) {
        throw new Error('Current password is required');
      }
      const isValid = await bcrypt.compare(currentPassword, patron.passwordHash);
      if (!isValid) throw new Error('Current password is incorrect');
    }

    const newHash = await bcrypt.hash(newPassword, 10);
    await this.patronRepo.update(id, {
      passwordHash: newHash,
      passwordAutoGenerated: false,
    });
  }

  async getStats(): Promise<{
    totalPatrons: number;
    activePatrons: number;
    todayEntries: number;
    todayExits: number;
  }> {
    const totalPatrons = await this.patronRepo.countActivePatrons();
    const activePatrons = await this.patronRepo.countActiveInside();
    
    let todayEntries = 0;
    let todayExits = 0;
    
    try {
      const dailyStats = await accessServiceClient.getDailyStats();
      todayEntries = dailyStats.today_entries || 0;
      todayExits = dailyStats.today_exits || 0;
    } catch (err: any) {
      console.error('[PatronService] Failed to fetch access stats:', err.message);
      // Fallback to 0, don't crash
    }
    
    return { totalPatrons, activePatrons, todayEntries, todayExits };
  }

  async getActivePatrons(): Promise<PatronPublicDto[]> {
    const patrons = await this.patronRepo.getActivePatrons();
    return await Promise.all(patrons.map((p) => this.toPatronPublic(p)));
  }

  async suspendCard(id: string, reason: string): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');
    
    if (patron.status === 'suspended') {
      throw new Error('Card is already suspended');
    }

    const updated = await this.patronRepo.update(id, {
      status: 'suspended',
      suspendedReason: reason,
    });

    return await this.toPatronPublic(updated!);
  }

  async renewCard(id: string): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    const updated = await this.patronRepo.update(id, {
      status: 'active',
      suspendedReason: null,
    });

    return await this.toPatronPublic(updated!);
  }

  async reportLostCard(id: string): Promise<PatronPublicDto> {
    const patron = await this.patronRepo.findById(id);
    if (!patron) throw new NotFoundError('Patron not found');

    const newCardNumber = `THV-${patron.studentCode}-LOST-${Date.now()}`;
    const updated = await this.patronRepo.update(id, {
      status: 'lost',
      cardNumber: newCardNumber,
    });

    return await this.toPatronPublic(updated!);
  }

  private async toPatronPublic(patron: any): Promise<PatronPublicDto> {
    let hasFace = false;
    try {
      hasFace = await faceServiceClient.checkEnrollment(patron.id);
    } catch (error) {
      // Default to false if face service is unavailable
    }

    return {
      id: patron.id,
      fullName: patron.fullName,
      studentCode: patron.studentCode,
      className: patron.className,
      course: patron.course ?? null,
      permanentAddress: patron.permanentAddress ?? null,
      identityNumber: patron.identityNumber,
      email: patron.email,
      phone: patron.phone,
      cardNumber: patron.cardNumber,
      issueDate: patron.issueDate,
      membershipExpiry: patron.membershipExpiry,
      status: patron.status,
      currentStatus: patron.currentStatus,
      createdAt: patron.createdAt,
      updatedAt: patron.updatedAt,
      hasFace,
      passwordAutoGenerated: patron.passwordAutoGenerated ?? true,
    };
  }
}
