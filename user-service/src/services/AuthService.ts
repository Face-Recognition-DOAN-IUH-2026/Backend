import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import axios from 'axios';
import crypto from 'crypto';
import { User, UserRole } from '../entities/User.entity';
import { UserRepository } from '../repositories/UserRepository';
import { RedisService } from './RedisService';
import { config } from '../config';
import { getServiceToken } from '../../../shared/auth';
import { CircuitBreaker } from '../../../shared/utils/circuitBreaker';
import { retryWithBackoff } from '../../../shared/utils/retryWithBackoff';
import {
  RegisterDto,
  LoginDto,
  AuthResponse,
  TokenPayload,
  UserPublicDto,
} from '../dto';
import { UnauthorizedError, ForbiddenError, ConflictError, NotFoundError, BadRequestError } from '../errors';

const notificationCircuit = new CircuitBreaker(5, 60_000);

async function postToNotification(path: string, body: Record<string, any>): Promise<any> {
  return retryWithBackoff(async () => {
    if (!notificationCircuit.canRequest()) {
      throw new Error('Notification service temporarily unavailable');
    }
    try {
      const res = await axios.post(
        `${config.notificationServiceUrl}${path}`,
        body,
        {
          headers: { 'Authorization': `Bearer ${getServiceToken('user-service', config.jwtSecret)}` },
          timeout: 5000,
        }
      );
      notificationCircuit.recordSuccess();
      return res;
    } catch (err: any) {
      if (err?.response?.status >= 500 || err?.code === 'ECONNABORTED' || err?.code === 'ECONNREFUSED') {
        notificationCircuit.recordFailure();
      }
      throw err;
    }
  }, 2, 500);
}

export class AuthService {
  constructor(
    private userRepo: UserRepository,
    private redis: RedisService,
  ) {}

  private normalizeEmail(email: string): string {
    return String(email || '').trim().toLowerCase();
  }

  private isValidEmail(email: string): boolean {
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    return emailRegex.test(email);
  }

  async register(dto: RegisterDto): Promise<AuthResponse> {
    if (!dto.email || dto.email.trim() === '') {
      throw new BadRequestError('Email is required');
    }
    
    dto.email = this.normalizeEmail(dto.email);
    if (!this.isValidEmail(dto.email)) {
      throw new BadRequestError('Invalid email format');
    }
    
    const DEFAULT_PASSWORD = '11111111';
    const useAutoPassword = !dto.password;
    const passwordToHash = dto.password ?? DEFAULT_PASSWORD;
    
    if (dto.password && dto.password.length < 6) {
      throw new BadRequestError('Password must be at least 6 characters');
    }
    
    if (dto.verificationToken) {
      const verified = await this.verifyPreRegisterToken(dto.email, dto.verificationToken);
      if (!verified) {
        throw new BadRequestError('Ma xac thuc khong hop le hoac da het han');
      }
      dto.skipVerification = true;
    }
    
    const existing = await this.userRepo.findByEmail(dto.email);
    if (existing) throw new ConflictError('Email already registered');

    const passwordHash = await bcrypt.hash(passwordToHash, 10);

    const userData: Partial<User> = {
      email: dto.email,
      passwordHash,
      fullName: dto.fullName ?? null,
      role: dto.role ?? 'user',
      passwordAutoGenerated: useAutoPassword,
      status: dto.skipVerification ? 'active' : 'unverified',
    };

    if (dto.role === UserRole.PATRON) {
      const dupCode = dto.studentCode
        ? await this.userRepo.findByStudentCode(dto.studentCode)
        : null;
      if (dupCode) throw new ConflictError('Student code already exists');

      Object.assign(userData, {
        studentCode: dto.studentCode ?? null,
        className: dto.className ?? null,
        course: dto.course ?? null,
        permanentAddress: dto.permanentAddress ?? null,
        cardNumber: dto.studentCode ? `THV-${dto.studentCode}` : null,
        membershipExpiry: dto.membershipExpiry ?? this.calculateExpiryFromCourse(dto.course),
        issueDate: new Date().toISOString().split('T')[0],
        phone: dto.phone ?? null,
      });
    }

    const user = await this.userRepo.create(userData);
    
    if (user.role === 'patron') {
      const { amqpClient } = require('../clients/AmqpClient');
      amqpClient.publish('user.registered', {
        userId: user.id,
        email: user.email,
        fullName: user.fullName,
        studentCode: user.studentCode,
        cardNumber: user.cardNumber,
        status: user.status,
      }).catch((e: any) => console.error('[AMQP] Failed to publish user.registered:', e.message));
    }

    if (!dto.skipVerification) {
      await this.sendVerificationEmail(user.email);
    }
    return this.buildAuthResponse(user);
  }

  async login(dto: LoginDto): Promise<AuthResponse> {
    let user: User | null = null;

    if (dto.studentCode) {
      user = await this.userRepo.findByStudentCode(dto.studentCode);
    } else if (dto.email) {
      dto.email = this.normalizeEmail(dto.email);
      user = await this.userRepo.findByEmail(dto.email);
    }

    if (!user) throw new UnauthorizedError('Invalid credentials');

    const valid = await bcrypt.compare(dto.password, user.passwordHash);
    if (!valid) throw new UnauthorizedError('Invalid password');

    if (user.status !== 'active') {
      throw new ForbiddenError('Account is disabled');
    }

    if (user.role === UserRole.PATRON && user.membershipExpiry) {
      const expiry = new Date(user.membershipExpiry);
      if (expiry < new Date()) throw new ForbiddenError('Membership has expired');
    }

    return this.buildAuthResponse(user);
  }

  async getUserById(id: string): Promise<UserPublicDto> {
    const user = await this.userRepo.findById(id);
    if (!user) throw new UnauthorizedError('User not found');
    return this.toPublic(user);
  }

  async refreshToken(refreshTokenStr: string): Promise<{ access_token: string; token_type: string }> {
    const payload = this.verifyToken(refreshTokenStr, 'refresh');
    const user = await this.userRepo.findById(payload.userId);
    if (!user) throw new UnauthorizedError('User not found');
    if (user.status !== 'active') throw new ForbiddenError('Account is disabled');
    if (user.role === UserRole.PATRON && user.membershipExpiry) {
      const expiry = new Date(user.membershipExpiry);
      if (expiry < new Date()) throw new ForbiddenError('Membership has expired');
    }
    const accessToken = this.generateToken(
      { userId: user.id, email: user.email, role: user.role, fullName: user.fullName },
      'access',
    );
    return { access_token: accessToken, token_type: 'bearer' };
  }

  async forgotPassword(email: string): Promise<void> {
    const normalizedEmail = email.trim().toLowerCase();
    console.log(`[ForgotPassword] Looking up email: ${normalizedEmail}`);
    const user = await this.userRepo.findByEmail(normalizedEmail);

    if (!user) {
      console.log(`[ForgotPassword] User not found for email: ${normalizedEmail}`);
      throw new NotFoundError('Khong tim thay tai khoan voi email nay');
    }

    console.log(`[ForgotPassword] User found: ${user.id}, status: ${user.status}`);
    if (user.status !== 'active') {
      throw new ForbiddenError('Tai khoan da bi khoa');
    }

    const code = crypto.randomInt(100000, 999999).toString();

    await this.redis.setPasswordResetCode(normalizedEmail, code);
    console.log(`[ForgotPassword] Code stored in Redis, calling notification-service at: ${config.notificationServiceUrl}`);

    try {
      await postToNotification('/internal/send-password-reset', { toEmail: normalizedEmail, code });
      console.log(`[ForgotPassword] Email sent successfully to ${normalizedEmail}`);
    } catch (e: any) {
      console.error('[ForgotPassword] Failed to send email:', e.response?.status, e.response?.data || e.message);
      throw new Error('Khong the gui email, vui long thu lai sau');
    }
  }

  async verifyResetCode(email: string, code: string): Promise<boolean> {
    const storedCode = await this.redis.getPasswordResetCode(email.toLowerCase());
    if (!storedCode || storedCode !== code) {
      return false;
    }
    return true;
  }

  async resetPassword(email: string, code: string, newPassword: string): Promise<void> {
    const isValid = await this.verifyResetCode(email, code);
    if (!isValid) {
      throw new UnauthorizedError('Ma reset khong hop le hoac da het han');
    }

    const user = await this.userRepo.findByEmail(email.toLowerCase());
    if (!user) {
      throw new NotFoundError('Khong tim thay tai khoan');
    }

    const passwordHash = await bcrypt.hash(newPassword, 10);
    await this.userRepo.update(user.id, { passwordHash, passwordAutoGenerated: false });

    await this.redis.deletePasswordResetCode(email.toLowerCase());
  }

  async sendPreRegisterOtp(email: string): Promise<void> {
    const normalizedEmail = email.trim().toLowerCase();
    const existing = await this.userRepo.findByEmail(normalizedEmail);
    if (existing) {
      throw new ConflictError('Email already registered');
    }
    const code = crypto.randomInt(100000, 999999).toString();
    await this.redis.setPreRegisterOtp(normalizedEmail, code);
    try {
      await postToNotification('/internal/send-email-verification', { toEmail: normalizedEmail, code });
    } catch (e: any) {
      console.error('[AuthService] Failed to send pre-register OTP:', e.response?.status, e.response?.data || e.message);
      throw new Error('Khong the gui ma OTP, vui long thu lai sau');
    }
  }

  async verifyPreRegisterOtp(email: string, code: string): Promise<string> {
    const normalizedEmail = email.trim().toLowerCase();
    const storedCode = await this.redis.getPreRegisterOtp(normalizedEmail);
    if (!storedCode || storedCode !== code) {
      throw new UnauthorizedError('Ma OTP khong hop le hoac da het han');
    }
    await this.redis.deletePreRegisterOtp(normalizedEmail);
    const token = crypto.randomBytes(32).toString('hex');
    await this.redis.setPreRegisterToken(normalizedEmail, token);
    return token;
  }

  async verifyPreRegisterToken(email: string, token: string): Promise<boolean> {
    const normalizedEmail = email.trim().toLowerCase();
    const stored = await this.redis.getPreRegisterToken(normalizedEmail);
    if (!stored || stored !== token) return false;
    await this.redis.deletePreRegisterToken(normalizedEmail);
    return true;
  }

  async sendVerificationEmail(email: string): Promise<void> {
    const normalizedEmail = email.trim().toLowerCase();
    const code = crypto.randomInt(100000, 999999).toString();

    await this.redis.setEmailVerificationCode(normalizedEmail, code);
    console.log(`[Verification] Code stored in Redis, calling notification-service`);

    try {
      await postToNotification('/internal/send-email-verification', { toEmail: normalizedEmail, code });
      console.log(`[Verification] Email sent successfully to ${normalizedEmail}`);
    } catch (e: any) {
      console.error('[Verification] Failed to send email:', e.response?.status, e.response?.data || e.message);
    }
  }

  async verifyEmail(email: string, code: string): Promise<void> {
    const normalizedEmail = email.trim().toLowerCase();
    const storedCode = await this.redis.getEmailVerificationCode(normalizedEmail);
    
    if (!storedCode || storedCode !== code) {
      throw new UnauthorizedError('Ma xac thuc khong hop le hoac da het han');
    }

    const user = await this.userRepo.findByEmail(normalizedEmail);
    if (!user) {
      throw new NotFoundError('Khong tim thay tai khoan');
    }

    await this.userRepo.update(user.id, { status: 'active' });
    await this.redis.deleteEmailVerificationCode(normalizedEmail);
  }

  async resendVerificationEmail(email: string): Promise<void> {
    const normalizedEmail = email.trim().toLowerCase();
    const user = await this.userRepo.findByEmail(normalizedEmail);
    if (!user) throw new NotFoundError('Khong tim thay tai khoan voi email nay');
    if (user.status === 'active') throw new BadRequestError('Tai khoan da duoc xac thuc');
    await this.sendVerificationEmail(normalizedEmail);
  }

  async requestEmailCorrection(currentEmail: string, newEmail: string): Promise<void> {
    const normalizedCurrent = currentEmail.trim().toLowerCase();
    const normalizedNew = newEmail.trim().toLowerCase();

    if (normalizedCurrent === normalizedNew) {
      throw new BadRequestError('Email moi phai khac email hien tai');
    }

    const user = await this.userRepo.findByEmail(normalizedCurrent);
    if (!user) throw new NotFoundError('Khong tim thay tai khoan voi email nay');
    if (user.status === 'unverified') {
      const existingNew = await this.userRepo.findByEmail(normalizedNew);
      if (existingNew) throw new BadRequestError('Email nay da duoc su dung');
      const code = crypto.randomInt(100000, 999999).toString();
      await this.redis.setEmailVerificationCode(normalizedNew, code);
      try {
        await postToNotification('/internal/send-email-verification', { toEmail: normalizedNew, code });
      } catch (e: any) {
        console.error('[AuthService] Failed to send email correction OTP:', e.response?.status, e.response?.data || e.message);
        throw new Error('Khong the gui email, vui long thu lai sau');
      }
    } else {
      throw new BadRequestError('Chi tai khoan chua xac thuc moi duoc doi email');
    }
  }

  async verifyEmailAndCorrect(currentEmail: string, newEmail: string, code: string): Promise<void> {
    const normalizedCurrent = currentEmail.trim().toLowerCase();
    const normalizedNew = newEmail.trim().toLowerCase();

    const user = await this.userRepo.findByEmail(normalizedCurrent);
    if (!user) throw new NotFoundError('Khong tim thay tai khoan voi email nay');
    if (user.status !== 'unverified') {
      throw new BadRequestError('Chi tai khoan chua xac thuc moi duoc doi email');
    }

    const storedCode = await this.redis.getEmailVerificationCode(normalizedNew);
    if (!storedCode || storedCode !== code) {
      throw new BadRequestError('Ma xac thuc khong hop le hoac da het han');
    }

    const existingNew = await this.userRepo.findByEmail(normalizedNew);
    if (existingNew) throw new BadRequestError('Email nay da duoc su dung');

    await this.userRepo.update(user.id, { email: normalizedNew, status: 'active' });
    await this.redis.deleteEmailVerificationCode(normalizedNew);
  }

  private calculateExpiryFromCourse(course: string | undefined): string {
    if (!course) return '2099-12-31';
    const rangeMatch = course.match(/(\d{4})\s*[-–]\s*(\d{4})/);
    if (rangeMatch) {
      const endYear = parseInt(rangeMatch[2], 10);
      return `${endYear}-12-31`;
    }
    const singleMatch = course.match(/(\d{4})/);
    if (singleMatch) {
      const year = parseInt(singleMatch[1], 10);
      return `${year}-12-31`;
    }
    return '2099-12-31';
  }

  verifyToken(token: string, expectedType?: 'access' | 'refresh'): TokenPayload {
    const secret = expectedType === 'refresh' ? config.jwtRefreshSecret : config.jwtSecret;
    try {
      const decoded: any = jwt.verify(token, secret);
      if (expectedType && decoded.typ !== expectedType) {
        throw new Error(`Invalid token type: expected ${expectedType}`);
      }
      return {
        userId: decoded.sub,
        email: decoded.email || '',
        role: decoded.roles?.[0] || 'user',
        fullName: decoded.full_name || null,
      };
    } catch (err: any) {
      if (err.message?.includes('Invalid token type')) throw err;
      throw new UnauthorizedError('Invalid or expired token');
    }
  }

  private buildAuthResponse(user: User): AuthResponse {
    const payload: TokenPayload = {
      userId: user.id,
      email: user.email,
      role: user.role,
      fullName: user.fullName,
    };
    return {
      access_token: this.generateToken(payload, 'access'),
      refresh_token: this.generateToken(payload, 'refresh'),
      token_type: 'bearer',
      user: this.toPublic(user),
    };
  }

  private generateToken(payload: TokenPayload, type: 'access' | 'refresh'): string {
    const now = Math.floor(Date.now() / 1000);
    const exp =
      type === 'refresh'
        ? now + config.jwtRefreshExpiresDays * 86400
        : now + config.jwtAccessExpiresMinutes * 60;
    const secret = type === 'refresh' ? config.jwtRefreshSecret : config.jwtSecret;

    const jwtPayload: Record<string, any> = {
      sub: payload.userId,
      email: payload.email,
      iss: config.jwtIssuer,
      aud: config.jwtAudience,
      exp,
      iat: now,
      roles: [payload.role],
      typ: type,
    };
    if (payload.fullName) jwtPayload.full_name = payload.fullName;

    return jwt.sign(jwtPayload, secret);
  }

  toPublic(user: User): UserPublicDto {
    const dto: UserPublicDto = {
      id: user.id,
      email: user.email,
      fullName: user.fullName,
      role: user.role,
    };
    if (user.studentCode) dto.studentCode = user.studentCode;
    if (user.className) dto.className = user.className;
    if (user.course) dto.course = user.course;
    if (user.permanentAddress) dto.permanentAddress = user.permanentAddress;
    if (user.identityNumber) dto.identityNumber = user.identityNumber;
    if (user.phone) dto.phone = user.phone;
    if (user.cardNumber) dto.cardNumber = user.cardNumber;
    if (user.issueDate) dto.issueDate = user.issueDate;
    if (user.membershipExpiry) dto.membershipExpiry = user.membershipExpiry;
    if (user.avatarUrl) dto.avatarUrl = user.avatarUrl;
    dto.status = user.status;
    dto.currentStatus = user.currentStatus;
    if (user.createdAt) dto.createdAt = user.createdAt.toISOString();
    if (user.updatedAt) dto.updatedAt = user.updatedAt.toISOString();
    return dto;
  }
}
