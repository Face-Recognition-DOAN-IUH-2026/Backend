import { AuthService } from '../../services/AuthService';
import { UserRepository } from '../../repositories/UserRepository';
import { RedisService } from '../../services/RedisService';

jest.mock('../../config', () => ({
  config: {
    jwtSecret: 'test-secret',
    jwtRefreshSecret: 'test-refresh-secret',
    jwtIssuer: 'test-issuer',
    jwtAudience: 'test-audience',
    jwtAccessExpiresMinutes: 15,
    jwtRefreshExpiresDays: 30,
  },
}));

jest.mock('../../repositories/UserRepository');
jest.mock('../../services/RedisService');

describe('AuthService - Registration', () => {
  let authService: AuthService;
  let userRepo: jest.Mocked<UserRepository>;
  let redis: jest.Mocked<RedisService>;

  beforeEach(() => {
    userRepo = {
      findByEmail: jest.fn(),
      findByStudentCode: jest.fn(),
      create: jest.fn(),
      findById: jest.fn(),
      update: jest.fn(),
    } as any;

    redis = {
      publishUserDeleted: jest.fn(),
      publishUserUpdated: jest.fn(),
      setPasswordResetCode: jest.fn(),
      getPasswordResetCode: jest.fn(),
      deletePasswordResetCode: jest.fn(),
    } as any;

    authService = new AuthService(userRepo, redis);
  });

  describe('Gap 6: Phone Field - Self-Registration', () => {
    it('should allow registration without phone field', async () => {
      userRepo.findByEmail.mockResolvedValue(null);
      userRepo.findByStudentCode.mockResolvedValue(null);
      userRepo.create.mockImplementation(async (data) => ({
        id: '1',
        ...data,
        createdAt: new Date(),
        updatedAt: new Date(),
      }) as any);

      const result = await authService.register({
        email: 'test@library.local',
        password: 'password123',
        fullName: 'Test User',
        role: 'patron',
        studentCode: 'SV001',
      });

      expect(result).toBeDefined();
      expect(result.user).toBeDefined();
      expect(userRepo.create).toHaveBeenCalled();
    });

    it('should store phone when provided in registration', async () => {
      userRepo.findByEmail.mockResolvedValue(null);
      userRepo.findByStudentCode.mockResolvedValue(null);
      userRepo.create.mockImplementation(async (data) => ({
        id: '1',
        ...data,
        createdAt: new Date(),
        updatedAt: new Date(),
      }) as any);

      await authService.register({
        email: 'test@library.local',
        password: 'password123',
        fullName: 'Test User',
        role: 'patron',
        studentCode: 'SV001',
        phone: '0901234567',
      });

      expect(userRepo.create).toHaveBeenCalledWith(
        expect.objectContaining({
          phone: '0901234567',
        })
      );
    });
  });

  describe('Gap 7: Auto-Generated Password', () => {
    it('should auto-generate password when not provided', async () => {
      userRepo.findByEmail.mockResolvedValue(null);
      userRepo.findByStudentCode.mockResolvedValue(null);
      userRepo.create.mockImplementation(async (data) => ({
        id: '1',
        ...data,
        createdAt: new Date(),
        updatedAt: new Date(),
      }) as any);

      const result = await authService.register({
        email: 'test@library.local',
        fullName: 'Test User',
        role: 'patron',
        studentCode: 'SV001',
      });

      expect(result).toBeDefined();
      expect(result.user).toBeDefined();
      expect(userRepo.create).toHaveBeenCalledWith(
        expect.objectContaining({
          passwordAutoGenerated: true,
        })
      );
    });

    it('should hash the auto-generated password', async () => {
      userRepo.findByEmail.mockResolvedValue(null);
      userRepo.findByStudentCode.mockResolvedValue(null);
      userRepo.create.mockImplementation(async (data) => ({
        id: '1',
        ...data,
        createdAt: new Date(),
        updatedAt: new Date(),
      }) as any);

      await authService.register({
        email: 'test@library.local',
        fullName: 'Test User',
        role: 'patron',
        studentCode: 'SV001',
      });

      const createCall = userRepo.create.mock.calls[0][0];
      expect(createCall.passwordHash).toBeDefined();
      expect(createCall.passwordHash).not.toBe('11111111');
      expect(createCall.passwordHash!.length).toBeGreaterThan(10);
    });

    it('should not set passwordAutoGenerated when password is provided', async () => {
      userRepo.findByEmail.mockResolvedValue(null);
      userRepo.findByStudentCode.mockResolvedValue(null);
      userRepo.create.mockImplementation(async (data) => ({
        id: '1',
        ...data,
        createdAt: new Date(),
        updatedAt: new Date(),
      }) as any);

      await authService.register({
        email: 'test@library.local',
        password: 'mypassword123',
        fullName: 'Test User',
        role: 'patron',
        studentCode: 'SV001',
      });

      expect(userRepo.create).toHaveBeenCalledWith(
        expect.objectContaining({
          passwordAutoGenerated: false,
        })
      );
    });
  });
});
