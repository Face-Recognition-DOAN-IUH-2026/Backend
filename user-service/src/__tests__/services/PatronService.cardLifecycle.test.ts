import { PatronService } from '../../services/PatronService';
import { PatronRepository } from '../../repositories/PatronRepository';
import { RedisService } from '../../services/RedisService';

jest.mock('../../repositories/PatronRepository');
jest.mock('../../services/RedisService');
jest.mock('../../clients/BorrowServiceClient');
jest.mock('../../clients/FaceServiceClient', () => ({
  faceServiceClient: {
    checkEnrollment: jest.fn().mockResolvedValue(false),
  },
}));
jest.mock('../../clients/AccessServiceClient', () => ({
  accessServiceClient: {
    getPatronStatus: jest.fn().mockResolvedValue('outside'),
    setPatronStatus: jest.fn().mockResolvedValue(undefined),
  },
}));

describe('PatronService - Card Lifecycle', () => {
  let patronService: PatronService;
  let patronRepo: jest.Mocked<PatronRepository>;
  let redis: jest.Mocked<RedisService>;

  beforeEach(() => {
    patronRepo = {
      findById: jest.fn(),
      findByStudentCode: jest.fn(),
      findByCardNumber: jest.fn(),
      create: jest.fn(),
      update: jest.fn(),
      findPatrons: jest.fn(),
      getActivePatrons: jest.fn(),
      countActivePatrons: jest.fn(),
      countActiveInside: jest.fn(),
      updateCurrentStatus: jest.fn(),
    } as any;

    redis = {
      publishUserDeleted: jest.fn(),
      publishUserUpdated: jest.fn(),
      setPasswordResetCode: jest.fn(),
      getPasswordResetCode: jest.fn(),
      deletePasswordResetCode: jest.fn(),
    } as any;

    patronService = new PatronService(patronRepo, redis);
  });

  describe('Gap 8: Card Lifecycle', () => {
    const mockPatron = {
      id: '1',
      studentCode: 'SV001',
      cardNumber: 'THV-SV001',
      status: 'active',
      fullName: 'Test User',
      email: 'test@library.local',
      className: 'CT001',
      course: '2024-2025',
      permanentAddress: 'Test Address',
      identityNumber: '123456789',
      phone: '0901234567',
      issueDate: '2024-01-01',
      membershipExpiry: '2025-12-31',
      currentStatus: 'outside',
      passwordHash: 'hashedpassword',
      passwordAutoGenerated: false,
      createdAt: new Date(),
      updatedAt: new Date(),
    };

    it('should suspend card when suspend method is called', async () => {
      patronRepo.findById.mockResolvedValue(mockPatron as any);
      patronRepo.update.mockImplementation(async (id, data) => ({
        ...mockPatron,
        ...data,
      }) as any);

      const result = await patronService.suspendCard('1', 'Violation of library rules');

      expect(result).toBeDefined();
      expect(result.status).toBe('suspended');
      expect(patronRepo.update).toHaveBeenCalledWith('1', expect.objectContaining({
        status: 'suspended',
        suspendedReason: 'Violation of library rules',
      }));
    });

    it('should renew card when renew method is called', async () => {
      const suspendedPatron = { ...mockPatron, status: 'suspended' };
      patronRepo.findById.mockResolvedValue(suspendedPatron as any);
      patronRepo.update.mockImplementation(async (id, data) => ({
        ...suspendedPatron,
        ...data,
      }) as any);

      const result = await patronService.renewCard('1');

      expect(result).toBeDefined();
      expect(result.status).toBe('active');
      expect(patronRepo.update).toHaveBeenCalledWith('1', expect.objectContaining({
        status: 'active',
        suspendedReason: null,
      }));
    });

    it('should mark card as lost and generate new card number', async () => {
      patronRepo.findById.mockResolvedValue(mockPatron as any);
      patronRepo.update.mockImplementation(async (id, data) => ({
        ...mockPatron,
        ...data,
      }) as any);

      const result = await patronService.reportLostCard('1');

      expect(result).toBeDefined();
      expect(result.status).toBe('lost');
      expect(result.cardNumber).not.toBe(mockPatron.cardNumber);
      expect(patronRepo.update).toHaveBeenCalledWith('1', expect.objectContaining({
        status: 'lost',
      }));
    });

    it('should not suspend already suspended card', async () => {
      const suspendedPatron = { ...mockPatron, status: 'suspended' };
      patronRepo.findById.mockResolvedValue(suspendedPatron as any);

      await expect(patronService.suspendCard('1', 'Already suspended'))
        .rejects.toThrow('Card is already suspended');
    });
  });
});
