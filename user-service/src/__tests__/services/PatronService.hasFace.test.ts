import { PatronService } from '../../services/PatronService';
import { PatronRepository } from '../../repositories/PatronRepository';
import { RedisService } from '../../services/RedisService';

jest.mock('../../repositories/PatronRepository');
jest.mock('../../services/RedisService');
jest.mock('../../clients/BorrowServiceClient');
jest.mock('../../clients/FaceServiceClient');

describe('PatronService - hasFace Integration', () => {
  let patronService: PatronService;
  let patronRepo: jest.Mocked<PatronRepository>;
  let redis: jest.Mocked<RedisService>;
  let faceServiceClient: any;

  beforeEach(() => {
    patronRepo = {
      findById: jest.fn(),
      findByStudentCode: jest.fn(),
      findByCardNumber: jest.fn(),
      create: jest.fn(),
      update: jest.fn(),
      findPatrons: jest.fn(),
      getActivePatrons: jest.fn(),
      countActivePatrons: jest.fn(),
      countActiveInside: jest.fn(),
      updateCurrentStatus: jest.fn(),
    } as any;

    redis = {
      publishUserDeleted: jest.fn(),
      publishUserUpdated: jest.fn(),
      setPasswordResetCode: jest.fn(),
      getPasswordResetCode: jest.fn(),
      deletePasswordResetCode: jest.fn(),
    } as any;

    faceServiceClient = require('../../clients/FaceServiceClient').faceServiceClient;
    faceServiceClient.checkEnrollment.mockResolvedValue(false);

    patronService = new PatronService(patronRepo, redis);
  });

  describe('Gap 9: hasFace Integration', () => {
    const mockPatron = {
      id: '1',
      studentCode: 'SV001',
      cardNumber: 'THV-SV001',
      status: 'active',
      fullName: 'Test User',
      email: 'test@library.local',
      className: 'CT001',
      course: '2024-2025',
      permanentAddress: 'Test Address',
      identityNumber: '123456789',
      phone: '0901234567',
      issueDate: '2024-01-01',
      membershipExpiry: '2025-12-31',
      currentStatus: 'outside',
      passwordHash: 'hashedpassword',
      passwordAutoGenerated: false,
      createdAt: new Date(),
      updatedAt: new Date(),
    };

    it('should return hasFace as true when patron has face enrolled', async () => {
      patronRepo.findById.mockResolvedValue(mockPatron as any);
      faceServiceClient.checkEnrollment.mockResolvedValue(true);

      const result = await patronService.getById('1');

      expect(result).toBeDefined();
      expect(result.hasFace).toBe(true);
      expect(faceServiceClient.checkEnrollment).toHaveBeenCalledWith('1');
    });

    it('should return hasFace as false when patron has no face enrolled', async () => {
      patronRepo.findById.mockResolvedValue(mockPatron as any);
      faceServiceClient.checkEnrollment.mockResolvedValue(false);

      const result = await patronService.getById('1');

      expect(result).toBeDefined();
      expect(result.hasFace).toBe(false);
    });

    it('should return hasFace as false when face service is unavailable', async () => {
      patronRepo.findById.mockResolvedValue(mockPatron as any);
      faceServiceClient.checkEnrollment.mockRejectedValue(new Error('Service unavailable'));

      const result = await patronService.getById('1');

      expect(result).toBeDefined();
      expect(result.hasFace).toBe(false);
    });
  });
});
